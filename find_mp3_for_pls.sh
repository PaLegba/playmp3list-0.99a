#!/bin/bash

# Проверка аргументов: должны быть указаны путь к каталогу и выходной файл
if [ "$#" -ne 2 ]; then
    echo "Использование: $0 <директория> <файл.pls>"
    exit 1
fi

SEARCH_DIR="$1"
OUTPUT_FILE="$2"

# Проверка, существует ли директория
if [ ! -d "$SEARCH_DIR" ]; then
    echo "Ошибка: Директория '$SEARCH_DIR' не найдена!"
    exit 1
fi

echo "Поиск MP3-файлов в $SEARCH_DIR..."

# Создаем или очищаем выходной файл перед записью
> "$OUTPUT_FILE"

# Находим файлы, обрабатывая как строчные, так и заглавные расширения,
# и записываем их абсолютные пути в выходной файл
find "$SEARCH_DIR" -type f \( -iname "*.mp3" \) -exec realpath {} \; > "$OUTPUT_FILE"

echo "Готово! Пути к файлам сохранены в: $OUTPUT_FILE"
